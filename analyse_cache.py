"""
analyse_cache.py - local analysis of an already-collected CDX cache. No network needed.

Answers three questions:
    1. How are product URLs structured? (so we know what to request individually)
    2. How bad is the parameter explosion? (how many URLs are the same product)
    3. What is the 2015 anomaly? (real data, or junk generated by parameters)

Usage:
    python analyse_cache.py --cache cdx_cache/sportsauthority.com.json
    python analyse_cache.py --cache cdx_cache/sportsauthority.com.json --year 2015

Works with both the old format (.json from v1) and the new one (.jsonl from v2).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit, parse_qsl


def stream_records(path: Path):
    """
    Reads records one at a time.

    For .jsonl - simply line by line.
    For .json (one large array) - by sequential decoding, so the whole list is
    never built in memory at once. A million and a half dictionaries in a list
    is several gigabytes of RAM; we do not need them, we are only counting.
    """
    if path.suffix == ".jsonl":
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if line:
                    yield json.loads(line)
        return

    text = path.read_text(encoding="utf-8")
    decoder = json.JSONDecoder()
    index = text.index("[") + 1
    length = len(text)
    while index < length:
        while index < length and text[index] in " \t\r\n,":
            index += 1
        if index >= length or text[index] == "]":
            break
        record, index = decoder.raw_decode(text, index)
        yield record


def main() -> int:
    parser = argparse.ArgumentParser(description="Local analysis of a CDX cache")
    parser.add_argument("--cache", required=True, help="path to a .json or .jsonl file")
    parser.add_argument("--year", default=None, help="restrict the analysis to one year")
    parser.add_argument("--top", type=int, default=25, help="how many rows to show")
    args = parser.parse_args()

    cache_path = Path(args.cache)
    if not cache_path.exists():
        print(f"No such file: {cache_path}")
        return 1

    total = 0
    with_query = 0
    first_segment = Counter()
    second_segment = Counter()
    param_names = Counter()
    unique_paths = set()          # URL WITHOUT parameters
    unique_full = set()           # URL WITH parameters
    year_counter = Counter()
    samples: list[str] = []

    for record in stream_records(cache_path):
        timestamp = record.get("timestamp", "")
        year = timestamp[:4]
        year_counter[year] += 1

        if args.year and year != args.year:
            continue

        total += 1
        url = record.get("original", "")
        parts = urlsplit(url)
        path = parts.path or "/"

        unique_paths.add((parts.netloc.replace("www.", ""), path))
        unique_full.add((parts.netloc.replace("www.", ""), path, parts.query))

        if parts.query:
            with_query += 1
            for name, _value in parse_qsl(parts.query, keep_blank_values=True):
                param_names[name] += 1

        segments = [s for s in path.split("/") if s]
        first_segment[segments[0] if segments else "(root)"] += 1
        if len(segments) > 1:
            second_segment[f"{segments[0]}/{segments[1]}"] += 1

        if len(samples) < 12 and parts.query:
            samples.append(url)

    if total == 0:
        print("No records matched the condition.")
        return 1

    print(f"\n{'='*70}")
    print(f"Records in selection: {total:,}" + (f"  (year {args.year})" if args.year else ""))
    print(f"{'='*70}")

    print(f"\nURLs with parameters (?...): {with_query:,}  ({100*with_query/total:.1f}%)")
    print(f"Unique URLs WITH parameters:    {len(unique_full):,}")
    print(f"Unique URLs WITHOUT parameters: {len(unique_paths):,}")
    if unique_paths:
        ratio = len(unique_full) / len(unique_paths)
        print(f"Inflation factor: {ratio:.1f}x")
        print("  (that many times more URLs than there are real pages)")

    print(f"\n--- First path segment (top {args.top}) ---")
    for name, count in first_segment.most_common(args.top):
        print(f"  {count:>9,}  /{name}")

    print(f"\n--- Two path segments (top {args.top}) ---")
    for name, count in second_segment.most_common(args.top):
        print(f"  {count:>9,}  /{name}")

    if param_names:
        print(f"\n--- Parameter names (top {args.top}) ---")
        for name, count in param_names.most_common(args.top):
            print(f"  {count:>9,}  {name}")

    if samples:
        print("\n--- Sample URLs with parameters ---")
        for url in samples:
            print(f"  {url[:150]}")

    if not args.year:
        print("\n--- Records per year (in the cache) ---")
        for year, count in sorted(year_counter.items()):
            print(f"  {year}  {count:>9,}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
